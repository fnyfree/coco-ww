        con_full = con_pre >= self.SK_R_EARLY_CON
        if self.ensure_r(sk, tag, self.SK_R_RESCUE, self.SK_R_ENSURE_CAP,
                         lambda rounds: self.sk_build_energy(sk, tag, rounds)):
            if con_full:
                gone_at = time.time()
                self.wait_until_time(gone_at + self.SK_R_SWITCH_FROM)
                self.macro_mark(f'{tag}R演出里切锁暝(R前协奏{con_pre:.2f})')
                ok = self.quick_switch(so, assume_con=True, time_out=self.SK_R_ANIM_CAP - self.SK_R_SWITCH_FROM)
