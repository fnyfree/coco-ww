    def so_4a_round(self, so, tag, stop=None):
        """一轮解伞形 4 段: 点到 SO_4A_TAP_UNTIL, 按住到 SO_4A_HOLD_UNTIL(都从第一下 A 起)。
        stop: 每帧看一次, 成立就提前收手(补妄执时用: 妄执一满就走)。返回 (提前收手没有, 耗时)。"""
