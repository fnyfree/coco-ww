        for i in range(1 + self.HEAVY_RETRIES):
            if self.hold_heavy(sk, self.SK_HEAVY_HOLD, self.SK_HEAVY_CAP,
                               tag=tag if i == 0 else f'{tag}重按#{i}'):
                return True
        return False

