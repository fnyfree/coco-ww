        while time.time() - start < cap:
            self.tap()
            taps += 1
            until = time.time() + max(0.0, self.A_INTERVAL - self.A_TAP)
            first = True
            while True:
                self.task.next_frame()
                if first:
                    self.hud_ok()
                    first = False
                hits = hits + 1 if done() else 0
                if hits >= 2:
                    self.macro_mark(f'{tag}(A x{taps},{time.time() - start:.2f}s)')
                    return True
                if time.time() >= until:
                    break
                self.macro_wait(0.01)
