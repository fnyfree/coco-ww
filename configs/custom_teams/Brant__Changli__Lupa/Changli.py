    def switch_with_lib_preinput(self, target, tag='切人+R'):
        """切人键和大招键一起递进去, 【大招演出直接盖住到场】也算成功。【全程不点击】。

        引擎的 switch_into_lib 判"到场"靠 HUD 读到目标 —— 但启动轴第 2->3 格露帕在
        HUD 上一帧都不出现就进了大招演出(视频 43.9 -> 44.0), HUD 整个消失, 那个判据
        会一直读不到, 白等 SWITCH_TIME_OUT 然后判失败、交接记账也不做。所以这里多认
        一种结局: R 已经发过 + HUD 连续 LIB_GONE_CONFIRM 帧不在 = 大招演出开始了。
        没改引擎里那一份, 是因为引擎有四份拷贝, 别的轴还靠它原来的语义。

        R 的放行门跟 switch_into_lib 一样: HUD 还明确显示离场角色就一发 R 都不发
        (不然放出来的是离场角色的大招), 另加 R_PREINPUT_MIN_LAG 的时间下界。

        Returns: 'lib' 大招已经起了 / 'field' 目标先到场了(R 可能还没出去) / None 切人失败
        """
        if target is None:
            return None
        source = self.cur if self.cur is not None else self
        if target is source:
            self.macro_mark(f'{tag}(already)')
            return 'field'
        entry = time.time()
        slot = target.index + 1
        team_size = len([c for c in self.task.chars if c is not None])
        n_key = 0
        n_lib = 0
        untrusted_hits = 0
        gone = 0
        r_open = False
        last = 0.0
        while time.time() - entry < self.SWITCH_TIME_OUT:
            now = time.time()
            if now - last >= self.SWITCH_KEY_INTERVAL:
                self.task.send_key(slot, down_time=self.SWITCH_KEY_DOWN_TIME)
                n_key += 1
                if r_open and now - entry >= self.R_PREINPUT_MIN_LAG:
                    target.send_liberation_key()
                    n_lib += 1
                last = now
            self.task.next_frame()
            in_team, index, count = self.task.in_team()
            if not (in_team and index == source.index):
                r_open = True
            if not in_team:
                gone = gone + 1 if n_lib > 0 else 0
                if gone >= self.LIB_GONE_CONFIRM:
                    self.handoff(source, target, False)
                    target.record_liberation_use()
                    self.macro_mark(f'{tag}(lib|{time.time() - entry:.2f}|'
                                    f'key x{n_key},R x{n_lib})')
                    return 'lib'
                continue
            gone = 0
            hit = index == target.index
            trusted = count >= team_size
            untrusted_hits = untrusted_hits + 1 if (hit and not trusted) else 0
            if hit and (trusted or untrusted_hits >= self.UNTRUSTED_CONFIRM):
                self.handoff(source, target, False)
                self.macro_mark(f'{tag}(field|{time.time() - entry:.2f}|'
                                f'key x{n_key},R x{n_lib})')
                return 'field'
        self.logger.warning(f'{tag}: {target.name} never came in and no liberation seen '
                            f'({n_key} keys, {n_lib} R)')
        self.macro_mark(f'{tag}(FAIL|key x{n_key},R x{n_lib})')
        return None

