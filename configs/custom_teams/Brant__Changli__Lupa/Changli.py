    def perform_opener(self, entry_char=None):
        """启动轴。由长离自己的 do_perform 调进来 —— 轴的第一个动作就是她的 A + E。

        Args:
            entry_char: 调用方自己 —— 框架就是因为他在场才调的 do_perform, 所以这是
                "现在场上是谁"最便宜也最可靠的答案。【不要让它去读屏判断】:
                in_team() 在战斗开局的头 0.8 秒会说谎(队伍 HUD 还在渐入)。
        """
        br = self.teammate('Brant')
        lu = self.teammate('Lupa')
        if br is None or lu is None:
            return False

        # 整段关掉脱战判定: 高频切人时 HUD 反复消失(大招演出), 战斗判定线程一误报
        # 就抛 NotInCombatException, 宏从中间断掉比打歪严重得多
        previous = getattr(self.task, 'skip_combat_check', False)
        self.task.skip_combat_check = True
        self.task._three_fire_macro_busy = True     # F 键监视线程靠它区分"手动处决"和"重开副本"
        self.cur = entry_char or self.on_field_char() or self
        self.poking = False
        raw_in_team, raw_index, raw_count = self.task.in_team()
        flags = ' '.join(f'{c.name}{"*" if c.is_current_char else ""}'
                         for c in self.task.chars if c is not None)
        self.logger.info(
            f'three-fire opener entry: {self.cur.name} '
            f'({"passed in by caller" if entry_char else "read off screen"}) | '
            f'in_team={raw_in_team} index={raw_index} count={raw_count} | flags: {flags}')
        try:
            self.macro_start()
            self.loop_count = 0
            # 【处决全程由宏自己决定】: 只在船长第一个强化 E 出伤后按一次(用户 2026-09-11 指定,
            # 见 L_BR_F_WINDOW), 框架切人时那一发一律关掉。内置 Brant / Lupa 的 check_f_on_switch
            # 本来就是 False, 长离的内置 do_perform 会把自己那个设成 True, 所以三个人都显式关一遍
            self.check_f_on_switch = False
            br.check_f_on_switch = False
            lu.check_f_on_switch = False
            # 【宏绕开了内置的 do_perform, 队友识别没人替我们做】: Brant.decide_teammate
            # 要靠它找到 char_lupa(内置版一堆判据的输入), 框架在宏散掉之后还会用到
            try:
                br.decide_teammate()
            except Exception as e:
                self.logger.debug(f'brant decide_teammate skipped: {e}')

            # 【开局长离不一定在场】: 框架可能因为别人先满足条件而先切了人。
            # 轴的第一个动作是她的 A + E, 所以先把自己换上来
            if self.cur is not self:
                self.quick_switch(self)

            marks = len(self.macro_marks)
            self.open_1_changli(br)
            self.logger.info(f'opener 1-CL timeline: {self.macro_timeline(marks)}')
            marks = len(self.macro_marks)

            how = self.open_2_brant(lu)
            self.open_3_lupa_r(how)
            self.logger.info(f'opener 2/3 timeline: {self.macro_timeline(marks)}')
            marks = len(self.macro_marks)

            self.open_4_changli_r(lu)
            self.logger.info(f'opener 4-CL-R timeline: {self.macro_timeline(marks)}')
            marks = len(self.macro_marks)

            self.open_tail(br, lu)
            self.logger.info(f'opener 5-15 timeline: {self.macro_timeline(marks)}')
            self.logger.info(
                f'opener total {self.time_elapsed_accounting_for_freeze(self.macro_t0):.2f}s '
                f'(wall {time.time() - self.macro_t0:.2f}s) — 视频里这一段净 12.4 秒')

            if self.CHAIN_LOOP_AFTER_OPENER:
                self.logger.info('chaining straight into the loop')
                self.run_loop_body(br, lu)
        finally:
            # 长按跨了好几个方法, 中途抛异常的话鼠标会一直按着, 下一个角色上场就是
            # 一直按住普攻。这里是唯一保证松手的地方
            self.release_attack()
            self.poking = False
            self.task.skip_combat_check = previous
            self.task._three_fire_macro_busy = False
        return True

