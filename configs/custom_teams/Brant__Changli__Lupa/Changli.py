    def perform_loop(self, entry_char=None):
        """循环轴。由长离自己的 do_perform 调进来 —— 一圈的首尾都在她身上。

        一圈 29.0 游戏秒(视频 112.2~203.0), 十六格, 序号见类文档那张表。
        """
        br = self.teammate('Brant')
        lu = self.teammate('Lupa')
        if br is None or lu is None:
            return False
        previous = getattr(self.task, 'skip_combat_check', False)
        self.task.skip_combat_check = True
        self.task._three_fire_macro_busy = True     # F 键监视线程靠它区分"手动处决"和"重开副本"
        self.cur = entry_char or self.on_field_char() or self
        self.poking = False
        try:
            self.macro_start()
            self.check_f_on_switch = False
            br.check_f_on_switch = False
            lu.check_f_on_switch = False
            try:
                br.decide_teammate()
            except Exception as e:
                self.logger.debug(f'brant decide_teammate skipped: {e}')
            # 【一圈的第一个动作是长离的预输入普攻】: 上一圈最后一格是船长, 他切回
            # 长离之后宏就返回了, 所以框架下一次调 do_perform 时她本来就在场。
            # 这句是给"宏中途散掉、框架自己切了人"之后的那一次兜底
            if self.cur is not self:
                self.quick_switch(self)
            self.run_loop_body(br, lu)
        finally:
            self.release_attack()
            self.poking = False
            self.task.skip_combat_check = previous
            self.task._three_fire_macro_busy = False
        return True

    def run_loop_body(self, br, lu):
        self.loop_count += 1
        n = self.loop_count
        marks = len(self.macro_marks)
        self.loop_1_pass(br, lu)
        self.logger.info(f'loop#{n} 1/2-PASS timeline: {self.macro_timeline(marks)}')
        marks = len(self.macro_marks)

        self.loop_3_brant_big(br)
        self.logger.info(f'loop#{n} 3-BRANT timeline: {self.macro_timeline(marks)}')
        marks = len(self.macro_marks)

        self.loop_4_changli_r(lu)
        self.logger.info(f'loop#{n} 4-CL-R timeline: {self.macro_timeline(marks)}')
        marks = len(self.macro_marks)

        self.loop_5_lupa_r(br)
        self.logger.info(f'loop#{n} 5-LU-R timeline: {self.macro_timeline(marks)}')
        marks = len(self.macro_marks)

        self.loop_tail(br, lu)
        self.logger.info(f'loop#{n} 6-16 timeline: {self.macro_timeline(marks)}')
        self.logger.info(
            f'loop#{n} total '
            f'{self.time_elapsed_accounting_for_freeze(self.macro_t0):.2f}s '
            f'(wall {time.time() - self.macro_t0:.2f}s) — 视频里一圈净 29.0 秒')

