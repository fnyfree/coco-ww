    def do_perform(self):
        """本队里长离驱动【两条轴】—— 启动轴和循环轴的入口都是她。

        【为什么两条轴都挂在她身上】: 一圈的最后一格是船长的 A×2, 打完他切回长离,
        宏返回时她在场; 下一次框架调 do_perform 又是她 —— 不用把循环入口借给别人。
        """
        if not self.is_in_three_fire:
            return super().do_perform()
        blocked = self.opener_blocked_by()
        if blocked is None:
            # 【标记要在跑之前落】: perform_opener 中途抛异常(脱战/任务被停)也不能
            # 让启动轴重跑 —— reset_state 会把 armed 重新置回来
            self.opener_armed = False
            self.last_opener = time.time()
            if self.perform_opener(self):
                return
            self.logger.warning('three-fire opener aborted, falling back to the native rotation')
            return super().do_perform()
        self.logger.info(f'three-fire: opener not pending ({blocked}), running the loop')
        if self.perform_loop(self):
            return
        return super().do_perform()

    def get_switch_priority(self, current_char=None, has_intro=False, target_low_con=False):
        """本队里由宏直接按数字键切人, 框架的选人只在宏散掉之后才起作用。

        【启动轴待跑时长离必须先上场】—— 轴的第一个动作是她的 A + E。本队里船长和
        露帕在启动轴待跑时都返回 NO(见各自文件), 所以这个 MUST 是必需的: 全队都是
        NO 的话框架只会打一下普攻原地打转。

        【不能直接用内置版的那句】: 内置 Changli.get_switch_priority 在
        "has_intro 且当前是 char_brant" 时返回 MUST —— 那是给内置轴用的, 本条轴上
        船长离场后该上谁由宏说了算, 留着会跟宏抢人。所以三火队里先判自己这一条。
        """
        if self.is_in_three_fire and self.opener_pending():
            return SwitchPriority.MUST
        return super().get_switch_priority(current_char, has_intro, target_low_con)

