        # 【窗口到 A2 递出去就结束, 不等它演完】(用户 2026-08-16: "达A2动作比较慢,
        # 如果抬手就切人那么她会在场上相对滞留比较长的时间")—— 这正是要的:
        # 她留在场上把 A2 演完的这段时间, 我们已经在别人身上做完了 爱A3E + 千QRE。
        # 【但这条链是有时限的】: 后面那格 达A34 要接在 A2 后面变成 A3, 中间的流程
