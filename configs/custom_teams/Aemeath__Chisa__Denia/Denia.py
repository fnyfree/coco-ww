    def wait_e_forte(self, char, cap=None, interval=None, tag='eForte'):
        """边点普攻边等【强化E 亮起】, 亮了立刻返回; 到上限也返回, 不把轴卡死。

        用户 2026-08-19 描述这一格的机制: 跳起来继续 A 会打出【空中下落攻击】,
        那一下正好把回路条打满 -> E 变成强化E -> 释放 -> 再 A 一下。
        【所以 E 不能按时间放】: 下落攻击什么时候落地、什么时候把条打满是浮动的,
        早按一点出来的就是普通 E, 这一格就废了(实机 2 轮里失败那轮正是没放出强化E)。

        【点击不能停】: 这一段的点击就是"继续A"本身 —— 下落攻击靠它打出来,
        条也靠它打满。2026-08-17 试过减少这一带的点击, 用户反馈"错的更多了"。

        【只在没准备好时才花时间】: 条已经满了就立刻返回, 快的轮次比固定窗口还快。
        判据用 is_e_forte_full()(找图 e_forte, 就是 E 强化态那个标记),
        是个小范围模板匹配, 比读 CD 的 OCR 便宜得多。
        """
        cap = self.O_CHI_E_FORTE_CAP if cap is None else cap
        interval = self.A_INTERVAL if interval is None else interval
        if cap <= 0:
            return False
        start = time.time()
        n = 0
        lit = False
        next_click = 0.0
        while time.time() - start < cap:
            now = time.time()
            if now >= next_click:
                self.click()
                n += 1
                next_click = now + interval
            self.task.next_frame()
            try:
                if char.is_e_forte_full():
                    lit = True
                    break
            except Exception:
                pass
        self.macro_mark(f'{tag}({"lit" if lit else "cap"},x{n},{time.time() - start:.2f}s)')
        return lit

