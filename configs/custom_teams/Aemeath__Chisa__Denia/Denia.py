    # ==================== 大招记账 ====================

    def note_lib1(self):
        """原版 Denia.do_perform 用 lib_1_casted / lib_2 决定下一发大招是不是收尾的
        那一发(Labels.denia_end_lib)。我们绕开了 click_liberation, 记账要自己补,
        否则宏一旦中断、控制权交回原版轮换, 她会拿着错的状态乱放。"""
        self.lib_1_casted = True

    def note_lib2(self):
        self.lib_2 = time.time()
        self.lib_1_casted = False

    # ==================== 框架接口 ====================

    def do_perform(self):
        """本队里达尼娅【不驱动任何一段轴】—— 启动轴由千咲驱动, 循环轴由爱弥斯驱动。

        走到这里说明宏散了(切人失败/脱战重进), 那就打一小段普攻把场子交出去,
        让爱弥斯或千咲重新拿到入口。【不要在这里跑循环轴】: 循环轴的第一步假设
        爱弥斯正在场上且是机甲形态, 从达尼娅这里起跑一定错位。
        """
        if self.is_in_denia_cycle:
            macro_owner_ready = self.opener_pending()
            self.logger.info(f'denia do_perform in denia cycle '
                             f'(opener pending={macro_owner_ready}) -> yielding the field')
            self.continues_normal_attack(0.6)
            return self.switch_next_char()
        return super().do_perform()

    def get_switch_priority(self, current_char=None, has_intro=False, target_low_con=False):
        """本队里由宏直接按数字键切人, 框架的选人只在宏散掉之后才起作用。

        启动轴待跑时返回 NO —— 轴的第一个动作是千咲的 E, 达尼娅不该抢先上场
        (框架至少还有千咲/爱弥斯两个候选, 不会因为这里返回 NO 就原地打转)。
        """
        if self.is_in_denia_cycle and self.opener_pending():
            return SwitchPriority.NO
        return super().get_switch_priority(current_char, has_intro, target_low_con)

    def on_combat_end(self, chars):
        self.release_attack()
        self.poking = False
        return super().on_combat_end(chars)
