        aem = self.teammate('Aemeath')
        chisa = self.teammate('Chisa')
        if aem is None or chisa is None:
            return False

        # 整段关掉脱战判定: 高频切人时 HUD 反复消失(大招演出), 战斗判定线程一误报
        # 就抛 NotInCombatException, 宏从中间断掉比打歪严重得多
        previous = getattr(self.task, 'skip_combat_check', False)
        self.task.skip_combat_check = True
        self.cur = entry_char or self.on_field_char() or self
        self.poking = False
        raw_in_team, raw_index, raw_count = self.task.in_team()
        flags = ' '.join(f'{c.name}{"*" if c.is_current_char else ""}'
                         for c in self.task.chars if c is not None)
        self.logger.info(
            f'denia opener entry: {self.cur.name} '
            f'({"passed in by caller" if entry_char else "read off screen"}) | '
            f'in_team={raw_in_team} index={raw_index} count={raw_count} | flags: {flags}')
        try:
            self.macro_start()
            self.check_f_on_switch = False
            aem.check_f_on_switch = False
            chisa.check_f_on_switch = False
            if self.USE_LOOP_AS_OPENER:
                # 【这条分支现在是关的】—— 见 USE_LOOP_AS_OPENER 的注释:
                # 开场凑不出机甲形态(A 满协奏会把 E 充成强化E), 已撤回
                self.logger.info('USE_LOOP_AS_OPENER: skipping the opener, '
                                 'running the loop from combat start')
                return self.perform_loop(entry_char=self.cur, cold=True)

            self.opener_seg1(chisa, aem)
            marks = len(self.macro_marks)
            self.logger.info(f'opener SEG1 '
                             f'{self.time_elapsed_accounting_for_freeze(self.macro_t0):.2f}s '
                             f'(wall {time.time() - self.macro_t0:.2f}s)')
            self.logger.info(f'opener SEG1 timeline: {self.macro_timeline()}')

            if self.opener_seg2(chisa, aem) is False:
                # 调试开关停在中途: 后面的 SEG3 和收尾爆发都不跑。
                # 仍然返回 True, 免得 Chisa.do_perform 把控制权交给原版轮换
                # 又开始自己切人 —— 那会把要观察的画面搞乱
                self.logger.info(f'opener SEG2 timeline: {self.macro_timeline(marks)}')
                self.logger.warning('DEBUG_STOP_AFTER_CHI_E is on -- opener stops here')
                return True
            self.logger.info(f'opener SEG2 timeline: {self.macro_timeline(marks)}')
            marks = len(self.macro_marks)

            self.opener_seg3(chisa, aem)
            self.logger.info(f'opener SEG3 timeline: {self.macro_timeline(marks)}')
            self.logger.info(
                f'opener total {self.time_elapsed_accounting_for_freeze(self.macro_t0):.2f}s '
                f'(wall {time.time() - self.macro_t0:.2f}s)')

            # 【直接调收尾, 不还给框架】: 走标记 + 等框架下一轮 do_perform 要白花
            # 约 0.7 秒(战斗循环重读当前角色 + 一次 check_outro 读屏), 全是读屏和调度
            marks = len(self.macro_marks)
            if hasattr(aem, 'perform_denia_burst'):
                self.logger.info('direct burst -> aemeath.perform_denia_burst')
                aem.perform_denia_burst(self, echo=True, a_window=0.0)
            else:
                self.logger.warning('Aemeath has no perform_denia_burst, closing burst skipped')
            self.logger.info(f'opener BURST timeline: {self.macro_timeline(marks)}')
        finally:
            # 长按跨了好几个方法, 中途抛异常的话鼠标会一直按着, 下一个角色上场就是
            # 一直按住普攻。这里是唯一保证松手的地方
            self.release_attack()
            self.poking = False
            self.task.skip_combat_check = previous
