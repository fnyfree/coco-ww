        self.macro_spam(self.L_AEM_EE_ANIM, self.A_INTERVAL_FAST, tag='aemEEanim')
        self.spam_segments(self.SEG_AEM, 1, tag='aemA2', interval=self.A_INTERVAL_FAST)

